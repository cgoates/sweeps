        {
            if( not isCartesian( domain ) )
                throw std::runtime_error( "Only Cartesian quadrature rules are implemented." );
            const size_t dim = param::dim( domain );

            const auto [quad_1d_pts, quad_1d_wts] = quad1d( order );
            const param::BaryCoordIsZeroVec interior( 2 * dim, false );

            util::iterateTensorProduct( util::IndexVec( dim, quad_1d_pts.size() ), [&]( const util::IndexVec& idx ) {
                Vector3dMax pt( dim );
                double wt = 1.0;
                for( size_t ii = 0; ii < dim; ++ii )
                {
                    pt( ii ) = quad_1d_pts.at( idx.at( ii ) );
                    wt *= quad_1d_wts.at( idx.at( ii ) );
                }
                points.emplace_back( domain, pt, interior );
                weights.push_back( wt );
            } );
        }

